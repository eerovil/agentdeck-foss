"""Where the heavy-command shim lives on disk, and how a worker reaches it.

Codex CLI has no equivalent of Claude Code's ``PreToolUse`` hook: nothing in
``codex``, ``codex app-server`` or ``~/.codex`` can see a shell command before
it runs.  So this half borrows the shape of ``agentdeck.gh_shim`` instead — a
generated directory first on the worker's PATH, holding one executable per
program a heavy command can start with.  The deck spawns these workers, so it
does not need reach into the repositories they work in; it governs the PATH of
the processes it starts.

Like the ``gh`` shim, the launchers are generated rather than checked in
because they must name *this* deck's interpreter absolutely, and a shim that
cannot be installed is not a spawn failure — the worker then reaches the real
programs exactly as it does today.
"""

from __future__ import annotations

import logging
import os
import shlex
import shutil
import stat
from pathlib import Path

from ..gh_shim.install import launcher_interpreter
from .classify import SHIMMED_PROGRAMS

log = logging.getLogger(__name__)

# Set in the environment of the real program the shim execs, so a suite runner
# that itself calls a shimmed program passes straight through. Only the command
# the worker actually asked for is judged; refusing a nested call would break
# the very build the deck just allowed.
RECURSION_GUARD = "AGENTDECK_HEAVY_SHIM_ACTIVE"
ACTIVE_DIR_ENV = "AGENTDECK_HEAVY_SHIM_LAUNCHER_DIR"

SHIM_DIR_ENV = "AGENTDECK_HEAVY_SHIM_DIR"

# Exit code for a command this shim declined to run. Distinct from the exit
# codes the shadowed programs use for a failing suite, so a caller can tell
# "your tests failed" from "the deck said queue it", and deliberately not 0:
# a refusal that looks like a green suite is the worst outcome available.
EXIT_REFUSED = 75
EXIT_NOT_FOUND = 127

# The launcher runs the shim through `-c` rather than `-m` so that it can
# survive its own absence. A half-deployed deck — a launcher generated by a
# newer checkout, an interpreter whose AgentDeck predates this package — would
# otherwise leave the worker unable to run the program at all, and fail open is
# the whole bargain (#1287). An import that fails here runs the real program
# and says nothing; being silently unenforced is where Codex already was.
_INLINE = """import os, sys
program, arguments = sys.argv[1], sys.argv[2:]
try:
    from agentdeck.heavy_shim.main import main
except Exception:
    home = {directory!r}
    real_home = os.path.realpath(home)
    kept = [
        p for p in os.environ.get("PATH", os.defpath).split(os.pathsep)
        if p and os.path.realpath(p) != real_home
    ]
    os.environ["PATH"] = os.pathsep.join(kept)
    try:
        os.execvp(program, [program, *arguments])
    except OSError:
        sys.exit({not_found})
sys.exit(main([program, *arguments]))
"""

_SCRIPT = """#!/bin/sh
# Generated by agentdeck.heavy_shim.install — do not edit.
{active_dir_env}={directory}
export {active_dir_env}
exec {interpreter} -c {inline} {program} "$@"
"""

# The guard runs during interpreter startup in whatever Python the worker
# reached, so it can import nothing of AgentDeck's and must never raise. It
# carries `classify.py`'s own source rather than a copy of its rules.
_GUARD = '''"""Generated by agentdeck.heavy_shim.install — do not edit."""

_CLASSIFY = {classify}


def _agentdeck_heavy_guard():
    import os
    import sys

    for bypass in ("AGENTDECK_HEAVY_SLOT_HELD", "AGENTDECK_HEAVY_SHIM_ACTIVE"):
        if os.environ.get(bypass, "").strip() not in ("", "0"):
            return
    namespace = {{}}
    exec(compile(_CLASSIFY, "<agentdeck-heavy-classify>", "exec"), namespace)

    argv = list(sys.argv)
    candidates = []
    program = os.path.basename(argv[0] or "") if argv else ""
    if program and not program.startswith("-"):
        candidates.append(namespace["command_string"](program, argv[1:]))
    # `python -m pytest` has not rewritten sys.argv yet at startup, so the
    # module name is only in the interpreter's own command line.
    original = list(getattr(sys, "orig_argv", ()))
    if len(original) > 1:
        candidates.append(namespace["command_string"]("python", original[1:]))
    command = next((one for one in candidates if namespace["is_heavy"](one)), None)
    if command is None:
        return
    if not namespace["runtime_is_up"]():
        # No queue to take it. Refusing now would leave the worker unable to
        # test at all, which is the worse failure.
        return
    sys.stderr.write(namespace["queue_advice"](command, os.getcwd()) + "\\n")
    sys.stderr.flush()
    os._exit({refused})


def _agentdeck_run_local_sitecustomize():
    """Let a project's own ``sitecustomize`` still run behind this one."""
    import importlib.util
    import os
    import sys

    here = os.path.dirname(os.path.abspath(__file__))
    for entry in sys.path:
        root = os.getcwd() if not entry else entry
        if os.path.abspath(root) == here:
            continue
        candidate = os.path.join(root, "sitecustomize.py")
        if not os.path.isfile(candidate):
            continue
        spec = importlib.util.spec_from_file_location("sitecustomize", candidate)
        if spec is None or spec.loader is None:
            return
        # Execute the project's customization as the ordinary `sitecustomize`
        # module, preserving import identity, file metadata, and Python's
        # normal diagnostics.
        module = sys.modules[__name__]
        module.__file__ = candidate
        module.__cached__ = spec.cached
        module.__loader__ = spec.loader
        module.__package__ = spec.parent
        module.__spec__ = spec
        spec.loader.exec_module(module)
        return


try:
    _agentdeck_heavy_guard()
except SystemExit:
    raise
except BaseException:
    pass

_agentdeck_run_local_sitecustomize()
'''


def shim_dir() -> Path:
    """The directory whose executables are this shim."""
    configured = os.environ.get(SHIM_DIR_ENV)
    if configured:
        return Path(configured).expanduser()
    data_home = os.environ.get("XDG_DATA_HOME")
    root = Path(data_home).expanduser() if data_home else Path.home() / ".local" / "share"
    return root / "agentdeck" / "heavy-shim"


def ensure_shim(directory: Path | None = None) -> Path | None:
    """Write one launcher per shimmed program, or ``None`` if it cannot be.

    Failing to install is deliberately not an error worth failing a spawn over:
    the queue is then advisory for that worker, which is exactly where Codex
    already is, rather than the worker being unable to start at all.
    """
    interpreter = launcher_interpreter()
    if interpreter is None:
        return None
    target = shim_dir() if directory is None else directory
    try:
        target.mkdir(parents=True, exist_ok=True)
        for program in SHIMMED_PROGRAMS:
            path = target / program
            inline = _INLINE.format(directory=str(target), not_found=EXIT_NOT_FOUND)
            path.write_text(
                _SCRIPT.format(
                    interpreter=shlex.quote(str(interpreter)),
                    inline=shlex.quote(inline),
                    program=shlex.quote(program),
                    active_dir_env=ACTIVE_DIR_ENV,
                    directory=shlex.quote(str(target)),
                )
            )
            path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError as exc:
        log.warning("heavy-command shim could not be installed at %s: %s", target, exc)
        return None
    return target


def worker_path(environment: dict[str, str]) -> str:
    """``environment``'s PATH with the shim first, or unchanged if uninstallable."""
    directory = ensure_shim()
    existing = environment.get("PATH", os.defpath)
    if directory is None:
        return existing
    entries = [part for part in existing.split(os.pathsep) if part]
    home = str(directory)
    return os.pathsep.join([home, *(part for part in entries if part != home)])


def guard_dir(directory: Path | None = None) -> Path:
    """The directory whose ``sitecustomize`` is the PATH-proof half."""
    return (shim_dir() if directory is None else directory) / "python"


def ensure_python_guard(directory: Path | None = None) -> Path | None:
    """Write the ``sitecustomize`` guard, returning its directory or ``None``.

    PATH order is not the last word on this host. Codex runs every command as
    ``/bin/bash -lc`` — a *login* shell — and a profile that prepends
    ``~/.local/bin`` puts the real ``pytest`` and ``uv`` back in front of the
    shim. The ``gh`` shim never met this because ``gh`` lives in ``/usr/bin``
    and nothing shadows it; ``pytest`` is exactly the command that took this
    host down, so the shim alone would miss the case it exists for.

    Every Python the worker starts imports ``sitecustomize``, wherever its
    executable resolved from, so this reaches ``~/.local/bin/pytest``,
    ``uv run pytest`` and ``python -m pytest`` alike. It is not a second opinion
    about what "heavy" means: the generated file embeds ``classify.py``'s own
    source, so there is still one definition and one refusal message.
    """
    target = guard_dir(directory)
    try:
        source = (Path(__file__).parent / "classify.py").read_text()
        target.mkdir(parents=True, exist_ok=True)
        (target / "sitecustomize.py").write_text(
            _GUARD.format(classify=repr(source), refused=EXIT_REFUSED)
        )
    except OSError as exc:
        log.warning("heavy-command guard could not be installed at %s: %s", target, exc)
        return None
    return target


def worker_pythonpath(environment: dict[str, str]) -> str:
    """``environment``'s PYTHONPATH with the guard first, or unchanged."""
    directory = ensure_python_guard()
    existing = environment.get("PYTHONPATH", "")
    if directory is None:
        return existing
    # Empty PYTHONPATH entries mean the current working directory. Preserve
    # them when they were explicit; dropping one can hide a project's own
    # root-level `sitecustomize.py`.
    entries = existing.split(os.pathsep) if existing else []
    home = str(directory)
    return os.pathsep.join([home, *(part for part in entries if part != home)])


def real_program(program: str, environment: dict[str, str] | None = None) -> str | None:
    """Find the actual ``program``, skipping this shim's own directory.

    Resolution walks PATH rather than trusting a recorded location, because the
    binary a worker should reach is whichever one it would have reached without
    the shim in front of it.
    """
    env = os.environ if environment is None else environment
    homes = {
        Path(shim_dir()).resolve(),
        Path(env.get(ACTIVE_DIR_ENV, str(shim_dir()))).resolve(),
    }
    entries = [
        part
        for part in env.get("PATH", os.defpath).split(os.pathsep)
        if part and Path(part).resolve() not in homes
    ]
    return shutil.which(program, path=os.pathsep.join(entries))
